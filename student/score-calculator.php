<script>
const tracks = <?= json_encode($tracks, JSON_UNESCAPED_UNICODE) ?>;
const subjectLabels = <?= json_encode($subjectLabels, JSON_UNESCAPED_UNICODE) ?>;

function getWeights(track) {
    if (typeof track.weights === 'string') {
        try { return JSON.parse(track.weights); } catch (e) { return {}; }
    }
    return track.weights || {};
}

function handleTrackChange() {
    const select = document.getElementById('facultyTrack');
    if (!select || !tracks.length) return;
    const trackIndex = select.value;
    const track = tracks[trackIndex];
    if (!track) return;

    const weights = getWeights(track);
    const container = document.getElementById('score-inputs-container');
    container.innerHTML = '';

    // Generate input fields based on required subjects
    for (const subject in weights) {
        if (!weights[subject] || weights[subject] <= 0) continue;
        
        const label = subjectLabels[subject] || subject.toUpperCase();
        const weightPct = (weights[subject] * 100).toFixed(0);
        
        const div = document.createElement('div');
        div.innerHTML = `
            <label class="block text-navy-950 font-bold mb-1 flex items-center justify-between">
              <span class="truncate pr-2">${label}</span>
              <span class="text-[10px] text-pink-500 bg-pink-50 px-1.5 py-0.5 rounded shrink-0">${weightPct}%</span>
            </label>
            <input type="number" id="input-${subject}" data-subject="${subject}" min="0" max="100" step="0.01" class="score-input w-full bg-[#f8fafc] border border-[#dce4ef] rounded-lg px-3 py-2.5 text-navy-950 font-medium focus:outline-none focus:border-pink-500 focus:ring-2 focus:ring-pink-500/20 transition-all placeholder:text-[#cbd5e1]" placeholder="0.00" oninput="calculateScore()">
        `;
        container.appendChild(div);
    }
    
    // Attempt to restore previous values if possible, or leave empty
    calculateScore();
}

function calculateScore() {
    const select = document.getElementById('facultyTrack');
    if (!select || !tracks.length) return;
    const trackIndex = select.value;
    const track = tracks[trackIndex];
    const weights = getWeights(track);
    
    let total = 0;
    let allEmpty = true;
    
    for (const subject in weights) {
        if (!weights[subject] || weights[subject] <= 0) continue;
        const input = document.getElementById(`input-${subject}`);
        if (input && input.value !== '') {
            allEmpty = false;
            const val = parseFloat(input.value) || 0;
            total += val * weights[subject];
        }
    }

    const output = document.getElementById('totalScoreOutput');
    const badge = document.getElementById('chanceBadge');
    const advice = document.getElementById('chanceAdvice');
    const minScore = parseFloat(track.min_score) || 58;

    if (allEmpty) {
        output.innerText = '0.00%';
        badge.className = 'inline-flex items-center px-4 py-1.5 rounded-full text-xs font-bold bg-[#f1f5f9] text-[#65738a] border border-[#e8ecf2]';
        badge.innerHTML = 'กรุณากรอกคะแนนเพื่อประเมิน';
        advice.innerText = 'เลือกกลุ่มคณะและกรอกคะแนนคาดหวังหรือคะแนนจริงในแต่ละวิชา เพื่อดูโอกาสสอบติดของคุณ';
        return;
    }

    output.innerText = `${total.toFixed(2)}%`;

    if (total >= minScore + 5) {
        badge.className = 'inline-flex items-center px-4 py-1.5 rounded-full text-xs font-bold bg-green-500/20 text-green-400 border border-green-500/30';
        badge.innerText = '🎉 โอกาสสอบติด: สูงมาก';
        advice.innerText = 'คะแนนอยู่ในเกณฑ์ปลอดภัยสูงมาก แนะนำรักษามาตรฐานนี้ไว้และฝึกทำข้อสอบจับเวลาเพิ่มเติม';
    } else if (total >= minScore) {
        badge.className = 'inline-flex items-center px-4 py-1.5 rounded-full text-xs font-bold bg-amber-500/20 text-amber-400 border border-amber-500/30';
        badge.innerText = '⚖️ โอกาสสอบติด: ปานกลาง มีลุ้น';
        advice.innerText = `คะแนนปริ่มเกณฑ์ขั้นต่ำของปีก่อน (${minScore.toFixed(2)}%) ควรเร่งทำคะแนนเพิ่มในวิชาที่ค่าน้ำหนักสูงเพื่อความอุ่นใจ`;
    } else {
        badge.className = 'inline-flex items-center px-4 py-1.5 rounded-full text-xs font-bold bg-red-500/20 text-red-400 border border-red-500/30';
        badge.innerText = '⚠️ โอกาสสอบติด: มีความเสี่ยง';
        advice.innerText = `คะแนนยังต่ำกว่าเกณฑ์เฉลี่ย (${minScore.toFixed(2)}%) เร่งทบทวนเนื้อหาและฝึกทำข้อสอบอย่างเข้มข้นด่วน!`;
    }
}

// Initialize
if (document.getElementById('facultyTrack')) {
    handleTrackChange();
}
